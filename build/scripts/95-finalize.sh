#!/bin/bash
# Turn the built root into something ostree can commit:
#   * capture the /var state packages created into systemd-tmpfiles
#   * relocate the dpkg/apt database out of /var (ostree does not ship /var)
#   * lay down the ostree symlink farm and empty /var
# shellcheck source=build/scripts/lib.sh
. "${CTX:-/ctx}/build/scripts/lib.sh"
load_env

log "Finalizing the image for ostree"

apt-get clean
rm -rf /var/lib/apt/lists/* /var/cache/* /var/log/* /tmp/* /var/tmp/* 2>/dev/null || true

# --- capture /var ----------------------------------------------------------
# Debian maintainer scripts create directories AND symlinks under /var
# (ghostscript's CMap tree is the classic example, and CUPS depends on it).
# Everything that must survive is re-created by systemd-tmpfiles on first boot.
info "capturing /var into systemd-tmpfiles"
TMPFILES=/usr/lib/tmpfiles.d/ik-os-var.conf
PRUNE=( -not -path '/var/home*' -not -path '/var/roothome*' -not -path '/var/usrlocal*'
        -not -path '/var/opt*'  -not -path '/var/srv*'      -not -path '/var/mnt*'
        -not -path '/var/tmp*'  -not -path '/var/cache*'
        -not -path '/var/lib/dpkg*' -not -path '/var/lib/apt*' )
{
    echo "# Generated by build/scripts/95-finalize.sh — do not edit."
    echo "# ostree does not ship /var, so the state Debian packages created at"
    echo "# build time is re-created here on first boot."
    find /var -mindepth 1 -type d "${PRUNE[@]}" -printf 'd %p 0%m %U %G - -\n' | sort -u
    find /var -mindepth 1 -type l "${PRUNE[@]}" -printf 'L %p - - - - %l\n'    | sort -u
} > "$TMPFILES"
info "$(grep -c '^[dL]' "$TMPFILES") tmpfiles entries"

# Files (not just dirs/symlinks) that packages seeded into /var are preserved as
# tmpfiles "copy" sources under /usr/share/factory, the systemd-sanctioned way.
info "staging seeded /var files into /usr/share/factory"
mkdir -p /usr/share/factory/var
while IFS= read -r f; do
    rel="${f#/var/}"
    install -Dm"$(stat -c '%a' "$f")" "$f" "/usr/share/factory/var/${rel}"
    printf 'C /var/%s - - - -\n' "$rel" >> "$TMPFILES"
done < <(find /var -mindepth 1 -type f "${PRUNE[@]}" 2>/dev/null | sort)

# --- relocate the package database ----------------------------------------
# Fedora keeps the rpm db in /usr/lib/sysimage/rpm for exactly this reason.
# Debian's dpkg db lives in /var, which ostree discards, so move it into /usr
# and symlink it back. Without this, `apt`, `dpkg -l` and any derived build on
# top of ik-os stop working on the deployed system.
info "relocating the dpkg and apt database into /usr"
mkdir -p /usr/lib/dpkg /usr/lib/apt
[[ -d /var/lib/dpkg && ! -L /var/lib/dpkg ]] && cp -a /var/lib/dpkg/. /usr/lib/dpkg/
[[ -d /var/lib/apt  && ! -L /var/lib/apt  ]] && cp -a /var/lib/apt/.  /usr/lib/apt/
cat > /usr/lib/tmpfiles.d/ik-os-dpkg.conf <<'EOF'
# The package database is image content, not machine state.
L /var/lib/dpkg - - - - ../../usr/lib/dpkg
L /var/lib/apt  - - - - ../../usr/lib/apt
EOF

# --- per-machine key material (SDD §27) -----------------------------------
# The ssl-cert package generates a self-signed "snakeoil" certificate in its
# postinst. Shipping it would put the *same* private key on every ik-os machine.
# It is removed here and regenerated per installation by first boot.
rm -f /etc/ssl/private/ssl-cert-snakeoil.key /etc/ssl/certs/ssl-cert-snakeoil.pem
# Likewise for anything a package generated on its own.
find /etc -name 'ssh_host_*' -delete 2>/dev/null || true

# --- release manifest (SDD §41, §46) --------------------------------------
log "Writing the release manifest"
mkdir -p /usr/share/ik-os
dpkg-query --admindir=/usr/lib/dpkg -W \
    -f='${binary:Package}\t${Version}\t${Architecture}\n' | sort \
    > /usr/share/ik-os/packages.manifest
info "$(wc -l < /usr/share/ik-os/packages.manifest) packages recorded"
{
    cat /usr/share/ik-os/build-base.env
    cat /usr/share/ik-os/build-kernel.env
    cat /usr/share/ik-os/build-bootc.env
    # Comments stripped: build-secureboot.env explains itself for a human
    # reading it in the image, but release.env is also parsed by hand in
    # places and its comment budget is better spent elsewhere.
    grep -v '^#' /usr/share/ik-os/build-secureboot.env 2>/dev/null || true
    echo "IK_OS_VERSION=\"${IK_OS_VERSION:-dev}\""
    echo "IK_OS_BUILD_ID=\"${IK_OS_BUILD_ID:-local}\""
    echo "IK_OS_GIT_COMMIT=\"${SHA_HEAD_SHORT:-unknown}\""
    echo "IK_OS_CHANNEL=\"${IK_OS_CHANNEL:-testing}\"" 
} > /usr/share/ik-os/release.env
chmod 0644 /usr/share/ik-os/release.env

# --- ostree symlink farm ---------------------------------------------------
log "Laying down the ostree root"

# Debian's kernel postinst leaves /vmlinuz and /initrd.img pointing into /boot,
# which is empty here: the kernel lives beside its modules and the bootloader
# entry is written per deployment by bootc. Dangling links would only mislead.
rm -f /vmlinuz /vmlinuz.old /initrd.img /initrd.img.old
# These are replaced by the symlink farm below; deleting them here is the point.
# shellcheck disable=SC2114
rm -rf /boot /home /root /usr/local /srv /opt /mnt /var
mkdir -p /sysroot /boot /var

ln -sT sysroot/ostree   /ostree
ln -sT var/home         /home
ln -sT var/roothome     /root
ln -sT var/opt          /opt
ln -sT var/srv          /srv
ln -sT var/mnt          /mnt
ln -sT ../var/usrlocal  /usr/local

cat > /usr/lib/tmpfiles.d/ik-os-base-dirs.conf <<'EOF'
d /var/home     0755 root root -
d /var/opt      0755 root root -
d /var/srv      0755 root root -
d /var/mnt      0755 root root -
d /var/usrlocal 0755 root root -
d /var/roothome 0700 root root -
d /run/media    0755 root root -
EOF

# No machine identity in the image. The container runtime bind-mounts
# /etc/hostname during the build, so it can be neither removed nor truncated
# from in here — and for the same reason it is never committed to a layer.
: > /etc/machine-id
rm -f /etc/hostname 2>/dev/null || info "/etc/hostname is a build-time bind mount; not part of the image"

