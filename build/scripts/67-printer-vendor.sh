#!/bin/bash
# SDD §22 Level 3, §24 — vendor printer drivers, installed from pinned local
# packages captured by scripts/maintenance/fetch-brother-driver.sh.
#
# The vendor's own installer is deliberately NOT run here: it is interactive,
# downloads at run time (unreproducible), and calls lpadmin to create a queue
# for one specific printer — machine state, not image content.
#
# Neither are the .deb maintainer scripts (ADR 0008). Brother's postinst chains
# into cupswrappermfcl3740cdw, whose last two lines are unconditional:
#
#     if [ "$URI" = '' ]; then URI="usb://dev/usb/lp0"; fi
#     lpadmin -p ${printer_name} -E -v $URI -P $ppd_file_name
#
# It invents a USB URI when it cannot find the printer, so running it during a
# build bakes a bogus queue into the image. We unpack the payload and do the
# wiring ourselves, which is also what lets the driver live in /usr.
#
# No-op when nothing is vendored.
# shellcheck source=build/scripts/lib.sh
. "${CTX:-/ctx}/build/scripts/lib.sh"
load_env

VENDOR_DIR="${CTX}/packages/printing/vendor"

shopt -s nullglob
VENDOR_DEBS=( "${VENDOR_DIR}"/*/*.deb )
shopt -u nullglob

if (( ${#VENDOR_DEBS[@]} == 0 )); then
    info "no vendor printer drivers to install"
    return 0 2>/dev/null || exit 0
fi

log "Installing ${#VENDOR_DEBS[@]} vendor printer driver package(s)"

# --- provenance (SDD §24: validate origin) --------------------------------
for dir in "${VENDOR_DIR}"/*/; do
    [[ -f "${dir}SHA256SUMS" ]] || die "no SHA256SUMS in ${dir}.
       Vendor packages must be checksummed — re-run
       scripts/maintenance/fetch-brother-driver.sh to regenerate."
    ( cd "$dir" && sha256sum -c SHA256SUMS --quiet ) \
        || die "checksum mismatch in ${dir}. The vendored packages do not match
       SHA256SUMS — do not ship this image until that is explained."
    info "checksums verified: $(basename "$dir")"
done

# --- where the driver lives ------------------------------------------------
# Brother hardcodes /opt/brother/Printers/<model>/ — the CUPS wrapper recovers
# the printer name with s|^/opt/.*/Printers/||, so the path is load-bearing and
# cannot simply be moved to /usr.
#
# But /opt is a symlink to var/opt in an ostree layout and 95-finalize.sh empties
# /var, so anything unpacked there is deleted before the image is committed.
# Ship the tree in /usr/lib/opt (image content) and re-establish /opt/brother as
# a tmpfiles symlink on boot — the bootc idiom for vendor software in /opt.
OPT_STORE=/usr/lib/opt
TMPFILES=/usr/lib/tmpfiles.d/ik-os-printer-vendor.conf

case "$(dpkg --print-architecture)" in
    amd64) VENDOR_ARCH=x86_64 ;;
    i386)  VENDOR_ARCH=i686   ;;
    *)     die "Brother ships printer driver binaries for x86_64 and i686 only.
       This build targets $(dpkg --print-architecture), so the vendored driver
       cannot work. Remove packages/printing/vendor/brother or build on amd64." ;;
esac
info "vendor binaries: selecting the ${VENDOR_ARCH} set"

# --- unpack (payload only, never maintainer scripts) -----------------------
STAGE="$(mktemp -d)"
for deb in "${VENDOR_DEBS[@]}"; do
    info "unpacking $(basename "$deb")"
    dpkg-deb -x "$deb" "$STAGE"
done

[[ -d "${STAGE}/opt" ]] || die "vendored package(s) contain no /opt tree.
       67-printer-vendor.sh only knows how to place Brother's /opt layout.
       Inspect the payload with 'dpkg-deb -c' and extend this step."

# Anything the payload puts outside /opt is image content already and can be
# copied straight across (Brother uses this for nothing today; fail loudly if
# that changes rather than silently dropping files).
for top in "${STAGE}"/*/; do
    case "$(basename "$top")" in
        opt) ;;
        *) die "vendored payload contains $(basename "$top")/, which this step
       does not place. Extend 67-printer-vendor.sh before shipping it." ;;
    esac
done

mkdir -p "$OPT_STORE"
cp -a "${STAGE}/opt/." "${OPT_STORE}/"
rm -rf "$STAGE"

{
    echo "# Generated by build/scripts/67-printer-vendor.sh — do not edit."
    echo "# Vendor printer drivers hardcode /opt paths but must ship in /usr,"
    echo "# because ostree does not carry /var (and /opt -> var/opt)."
    for d in "${OPT_STORE}"/*/; do
        printf 'L /var/opt/%s - - - - %s%s\n' "$(basename "$d")" "$OPT_STORE/" "$(basename "$d")"
    done
} > "$TMPFILES"

# --- wire up each printer model -------------------------------------------
# Replaces the vendor postinst, minus the lpadmin call.
shopt -s nullglob
MODEL_DIRS=( "${OPT_STORE}"/brother/Printers/*/ )
shopt -u nullglob
(( ${#MODEL_DIRS[@]} )) || die "no printer model directories under
       ${OPT_STORE}/brother/Printers — the payload layout is not what
       67-printer-vendor.sh expects."

install -d /usr/share/ppd/Brother /usr/share/cups/model/Brother /usr/lib/cups/filter

MODELS=()
for dir in "${MODEL_DIRS[@]}"; do
    model="$(basename "$dir")"
    MODELS+=( "$model" )
    log "Wiring printer model ${model}"

    # The runtime path, i.e. what everything must refer to. Resolves through the
    # tmpfiles symlink above once the system is booted.
    runtime="/opt/brother/Printers/${model}"

    # 1. Architecture symlinks the postinst would have made. Relative, so they
    #    stay valid both in /usr/lib/opt and under /opt at runtime.
    for tool in "brmfc${model}filter" "brprintconf_${model}" "br${model}filter"; do
        if [[ -f "${dir}lpd/${VENDOR_ARCH}/${tool}" ]]; then
            ln -sfn "${VENDOR_ARCH}/${tool}" "${dir}lpd/${tool}"
            info "  lpd/${tool} -> ${VENDOR_ARCH}/${tool}"
        fi
    done

    # 2. PPD into both locations CUPS searches.
    for ppd in "${dir}cupswrapper/"*.ppd; do
        [[ -f "$ppd" ]] || continue
        install -Dm644 "$ppd" "/usr/share/ppd/Brother/$(basename "$ppd")"
        install -Dm644 "$ppd" "/usr/share/cups/model/Brother/$(basename "$ppd")"
        info "  PPD: $(basename "$ppd")"
    done

    # 3. The CUPS filter. The symlink TARGET must be the /opt path: the wrapper
    #    calls readlink($0) on itself and strips ^/opt/.*/Printers/ to learn its
    #    own model name. Point it at /usr and it computes a garbage model and
    #    fails at print time. It is therefore dangling until first boot — by
    #    design; the check below validates the real file in /usr instead.
    for wrapper in "${dir}cupswrapper/brother_lpdwrapper_"*; do
        [[ -f "$wrapper" ]] || continue
        name="$(basename "$wrapper")"
        chmod 755 "$wrapper"
        ln -sfn "${runtime}/cupswrapper/${name}" "/usr/lib/cups/filter/${name}"
        info "  filter: /usr/lib/cups/filter/${name} -> ${runtime}/cupswrapper/${name}"
    done

    # 4. brprintconf on PATH, as the postinst does.
    if [[ -e "${dir}lpd/brprintconf_${model}" ]]; then
        ln -sfn "${runtime}/lpd/brprintconf_${model}" "/usr/bin/brprintconf_${model}"
    fi
done

# --- prove the filters actually run (SDD §24: dependency compatibility) ----
# Brother's packages are tagged Architecture: i386 but ship both x86_64 and i686
# binaries, and they declare almost no dependencies. A plain install "succeeds"
# and then the CUPS filter fails at print time with a missing shared library.
# Check the binaries we actually wired up; the other architecture's are dead
# weight we neither select nor link, so their libraries are irrelevant.
log "Verifying vendor driver binaries resolve their libraries"
case "$VENDOR_ARCH" in
    x86_64) OTHER_ARCH=i686   ;;
    i686)   OTHER_ARCH=x86_64 ;;
esac

MISSING=0 CHECKED=0 SKIPPED=0
while IFS= read -r bin; do
    if [[ "$bin" == */${OTHER_ARCH}/* ]]; then
        SKIPPED=$(( SKIPPED + 1 ))
        continue
    fi
    output_matches_fixed 'ELF' file "$bin" || continue
    CHECKED=$(( CHECKED + 1 ))
    if output_matches_fixed 'not found' ldd "$bin"; then
        info "MISSING LIBRARIES: ${bin}"
        ldd "$bin" 2>/dev/null | grep 'not found' | sed 's/^/        /'
        MISSING=1
    fi
done < <(find "$OPT_STORE" -type f -perm -u+x 2>/dev/null | sort)

info "${CHECKED} binaries checked, ${SKIPPED} skipped (${OTHER_ARCH}, not linked)"
(( MISSING == 0 )) || die "a vendor printer filter cannot resolve its shared
       libraries. It would install cleanly and then fail at print time.
       Add the missing library packages to packages/printing/packages.list."

# --- assert we did not bake a queue (SDD §23) ------------------------------
# The whole reason the maintainer scripts are skipped. Prove it held.
if [[ -s /etc/cups/printers.conf ]]; then
    die "/etc/cups/printers.conf is non-empty: a print queue was baked into the
       image. Queue creation is per-machine state and belongs to first boot or
       GNOME Settings (SDD §23)."
fi
info "no print queue created: that is per-machine state (SDD §23)"

# --- record what shipped ---------------------------------------------------
mkdir -p /usr/share/ik-os
{
    echo "# Vendor printer drivers baked into this image (SDD §24)"
    echo "# Packages:"
    for d in "${VENDOR_DEBS[@]}"; do echo "#   $(basename "$d")"; done
    echo "# Models (use these PPDs when adding a queue):"
    for m in "${MODELS[@]}"; do echo "$m"; done
} > /usr/share/ik-os/printer-drivers.list

log "Vendor printer drivers ready: ${MODELS[*]}"
